class ReliableMessageHelper(ABC):
    """Helper interface for reliable message management.

    Manages reliable message factories and provides core functionality for:
    - Creating reliable messages (secure message + signature)
    - Parsing raw reliable message data into strongly-typed `ReliableMessage` instances

    ReliableMessage represents a signed secure message (SecureMessage after signing)
    that ensures message integrity and authenticity (non-repudiation).
    """

    @abstractmethod
    def set_reliable_message_factory(self, factory: ReliableMessageFactory):
        """Set the reliable message factory.

        :param factory: factory to be registered
        """
        raise NotImplementedError(
            f'Not implemented: {type(self).__module__}.{type(self).__name__}.set_reliable_message_factory()'
        )

    @abstractmethod
    def get_reliable_message_factory(self) -> Optional[ReliableMessageFactory]:
        """Get the reliable message factory.

        :return: registered `ReliableMessageFactory`, or None if not registered
        """
        raise NotImplementedError(
            f'Not implemented: {type(self).__module__}.{type(self).__name__}.get_reliable_message_factory()'
        )

    @abstractmethod
    def create_reliable_message(self, s_msg: SecureMessage, signature: bytes):
        """Create a reliable message from secure message, adding 'signature'.

        Signs the encrypted content data with the sender's private key, forming
        the digital signature for authenticity and integrity verification.

        :param s_msg:     is the encrypted secure message.
        :param signature: is the signature of the encrypted content data.
        :return: a new `ReliableMessage` instance.
        """
        raise NotImplementedError(
            f'Not implemented: {type(self).__module__}.{type(self).__name__}.create_reliable_message()'
        )

    @abstractmethod
    def parse_reliable_message(self, msg: Any) -> Optional[ReliableMessage]:
        """Parses raw reliable message data into a strongly-typed `ReliableMessage` instance.

        Converts arbitrary raw reliable message data (e.g., map, JSON string) into a
        valid ReliableMessage object for signature verification and decryption.

        :param msg: raw reliable message data to parse
        :return: parsed `ReliableMessage` instance (None if parsing fails)
        """
        raise NotImplementedError(
            f'Not implemented: {type(self).__module__}.{type(self).__name__}.parse_reliable_message()'
        )


class ReliableMessageExtension:

    @property
    def reliable_helper(self) -> Optional[ReliableMessageHelper]:
        """ Get reliable message helper """
        raise NotImplementedError(
            f'Not implemented: {type(self).__module__}.{type(self).__name__}.reliable_helper getter'
        )

    @reliable_helper.setter
    def reliable_helper(self, helper: ReliableMessageHelper):
        """ Set reliable message helper """
        raise NotImplementedError(
            f'Not implemented: {type(self).__module__}.{type(self).__name__}.reliable_helper setter'
        )


shared_message_extensions.reliable_helper: Optional[ReliableMessageHelper] = None


def message_extensions() -> ReliableMessageExtension:
    return shared_message_extensions


def reliable_helper() -> ReliableMessageHelper:
    ext = message_extensions()
    return ext.reliable_helper
